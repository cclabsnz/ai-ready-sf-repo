#!/usr/bin/env python3
"""Render design.md from a design.json record. stdlib only.

A single renderer shared by the writers: framework/skills/solution-design/scripts/write_design.py
renders the draft, and promotion re-renders the confirmed record from it, so design.md always
states what design.json holds.

render_md(doc): doc is a design record that has already passed tools/designs/validate_design.py.
The fixed text is neutral: it names the option the assistant recommended and says that a named
owner confirms an option at promotion.
"""


def cell(v):
    """One markdown table cell: backslashes escaped first, then pipes; newlines become spaces."""
    return "" if v is None else str(v).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def render_md(doc):
    st = doc["provenance"]["indexStamp"]
    opts = doc["options"]
    by_id = {o["id"]: o for o in opts}
    rec = doc["recommendation"]
    lines = ["# Design: %s %s" % (doc["storyId"], doc["slug"]), "",
             "Status: %s. Index commit `%s`, index version %s, built %s." % (
                 doc["status"], str(st.get("commit"))[:12], st.get("indexVersion", "unknown"),
                 st.get("builtAt", "unknown")),
             "", "## Options", "",
             "| Option | Title | Do nothing | Summary | Impact summary |",
             "|---|---|---|---|---|"]
    for o in opts:
        lines.append("| %s | %s | %s | %s | %s |" % (
            o["id"], cell(o["title"]), "yes" if o["doNothing"] else "no", cell(o["summary"]),
            cell(o["impactSummary"])))
    lines += ["", "## Trade-offs"]
    for o in opts:
        lines += ["", "### %s: %s" % (o["id"], o["title"]), "", "| Criterion | Note |", "|---|---|"]
        lines += ["| %s | %s |" % (t["criterion"], cell(t["note"])) for t in o["tradeOffs"]]
    chosen = by_id[rec["optionId"]]
    lines += ["", "## Recommendation", "",
              "Recommended option: %s (%s). Recommended by: assistant. This is provisional until a "
              "named owner confirms an option at promotion." % (chosen["id"], chosen["title"]),
              "", "Reasons:", ""]
    lines += ["- %s" % r.replace("\n", " ") for r in rec["reasons"]]
    lines += ["", "## Components"]
    for o in opts:
        lines += ["", "### %s: %s" % (o["id"], o["title"]), ""]
        if not o["components"]:
            lines.append("- none: the do-nothing option changes no metadata")
            continue
        lines += ["| Component | Type | Change | Evidence | Confidence |", "|---|---|---|---|---|"]
        for c in o["components"]:
            ev = "`%s`" % c["evidence"] if c["evidence"] else "none"
            lines.append("| `%s` | %s | %s | %s | %s |" % (
                cell(c["api"]), cell(c["type"]), c["changeType"], ev, c["confidence"]))
    lines += ["", "_Generated by write_design.py from design.json. The options, trade-offs and reasons "
              "are the assistant's; the components are checked against the index._", ""]
    return "\n".join(lines)
