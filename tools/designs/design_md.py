#!/usr/bin/env python3
"""Render design.md from a design.json record. stdlib only.

A single renderer shared by the writers: framework/skills/solution-design/scripts/write_design.py
renders the draft, and promotion re-renders the confirmed record from it, so design.md always
states what design.json holds.

render_md(doc): doc is a design record that has already passed tools/designs/validate_design.py.
The fixed text is neutral: it names the option the assistant recommended and says that a named
owner confirms an option at promotion. A confirmed record (status confirmed) states the confirmer
and the chosen option in the status line and the Recommendation section, marks the chosen option
"(chosen)" in the options table, and drops the provisional wording. Draft output is unchanged.
"""


def cell(v):
    """One markdown table cell: backslashes escaped first, then pipes; newlines become spaces."""
    return "" if v is None else str(v).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def render_md(doc):
    st = doc["provenance"]["indexStamp"]
    opts = doc["options"]
    by_id = {o["id"]: o for o in opts}
    rec = doc["recommendation"]
    confirmed = doc["status"] == "confirmed"
    status = "Status: %s." % doc["status"]
    if confirmed:
        status += " Confirmed by: %s. Chosen option: %s." % (
            cell(doc["confirmedBy"]), doc["chosenOption"])
    lines = ["# Design: %s %s" % (doc["storyId"], doc["slug"]), "",
             "%s Index commit `%s`, index version %s, built %s." % (
                 status, str(st.get("commit"))[:12], st.get("indexVersion", "unknown"),
                 st.get("builtAt", "unknown")),
             "", "## Options", "",
             "| Option | Title | Do nothing | Summary | Impact summary |",
             "|---|---|---|---|---|"]
    for o in opts:
        oid = o["id"]
        if confirmed and oid == doc["chosenOption"]:
            oid += " (chosen)"
        lines.append("| %s | %s | %s | %s | %s |" % (
            oid, cell(o["title"]), "yes" if o["doNothing"] else "no", cell(o["summary"]),
            cell(o["impactSummary"])))
    lines += ["", "## Trade-offs"]
    for o in opts:
        lines += ["", "### %s: %s" % (o["id"], o["title"]), "", "| Criterion | Note |", "|---|---|"]
        lines += ["| %s | %s |" % (t["criterion"], cell(t["note"])) for t in o["tradeOffs"]]
    recommended = by_id[rec["optionId"]]
    if confirmed:
        picked = by_id[doc["chosenOption"]]
        text = ("Recommended option: %s (%s). Recommended by: assistant. Chosen option: %s (%s), "
                "confirmed by %s at promotion." % (
                    recommended["id"], recommended["title"], picked["id"], picked["title"],
                    cell(doc["confirmedBy"])))
    else:
        text = ("Recommended option: %s (%s). Recommended by: assistant. This is provisional until a "
                "named owner confirms an option at promotion." % (recommended["id"], recommended["title"]))
    lines += ["", "## Recommendation", "", text, "", "Reasons:", ""]
    lines += ["- %s" % r.replace("\n", " ") for r in rec["reasons"]]
    lines += ["", "## Components"]
    for o in opts:
        lines += ["", "### %s: %s" % (o["id"], o["title"]), ""]
        if not o["components"]:
            lines.append("- none: the do-nothing option changes no metadata")
            continue
        lines += ["| Component | Type | Change | Evidence | Confidence |", "|---|---|---|---|---|"]
        for c in o["components"]:
            ev = "`%s`" % c["evidence"] if c["evidence"] else "none"
            lines.append("| `%s` | %s | %s | %s | %s |" % (
                cell(c["api"]), cell(c["type"]), c["changeType"], ev, c["confidence"]))
    if confirmed:
        lines += ["", "_Re-rendered by promote.py from the confirmed design.json. The options, "
                  "trade-offs and reasons are the assistant's; the components are checked against "
                  "the index; the chosen option and the confirmer are recorded at promotion._", ""]
    else:
        lines += ["", "_Generated by write_design.py from design.json. The options, trade-offs and "
                  "reasons are the assistant's; the components are checked against the index._", ""]
    return "\n".join(lines)
