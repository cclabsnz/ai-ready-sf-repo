#!/usr/bin/env python3
"""Render .claude/ and .github/ from framework/. One source tree, two outputs.

  framework/rules/*.md         -> CLAUDE.md imports + .github/instructions/*.instructions.md
  framework/knowledge/*.md     -> .claude/knowledge/ + .github/knowledge/ + generated README index
  framework/skills/<n>/        -> .claude/skills/<n>/ + .github/skills/<n>/
  framework/agents/<n>.md      -> .claude/agents/<n>.md + .github/agents/<n>.agent.md

Run with --check in CI: exit 1 if the committed outputs differ from a fresh render.
"""
import argparse
import filecmp
import os
import re
import shutil
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FW = os.path.join(ROOT, "framework")


def front_matter(path):
    with open(path, encoding="utf-8") as fh:
        txt = fh.read()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", txt, re.S)
    if not m:
        return {}, txt
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip().strip('"')
    return meta, m.group(2)


def render(out_root):
    claude = os.path.join(out_root, ".claude")
    gh = os.path.join(out_root, ".github")
    for d in ("knowledge", "skills", "agents"):
        os.makedirs(os.path.join(claude, d), exist_ok=True)
    for d in ("instructions", "knowledge", "skills", "agents"):
        os.makedirs(os.path.join(gh, d), exist_ok=True)

    # Rules
    imports = []
    for f in sorted(os.listdir(os.path.join(FW, "rules"))):
        if not f.endswith(".md"):
            continue
        meta, body = front_matter(os.path.join(FW, "rules", f))
        scope = meta.get("scope", "**")
        name = f[:-3]
        with open(os.path.join(gh, "instructions", f"{name}.instructions.md"), "w", encoding="utf-8") as fh:
            fh.write(f"---\napplyTo: \"{scope}\"\n---\n{body}")
        imports.append(f"@.github/instructions/{name}.instructions.md")
    with open(os.path.join(out_root, "CLAUDE.md"), "w", encoding="utf-8") as fh:
        fh.write("# Project rules (generated by tools/build/render.py; edit framework/rules/)\n\n"
                 "Precedence: the checked-out build is the only source of truth. Knowledge files are leads to re-verify. "
                 "Anything countable comes from `tools/index/query.py`, never from a file.\n\n"
                 + "\n".join(imports) + "\n")

    # Knowledge + index
    rows = []
    for f in sorted(os.listdir(os.path.join(FW, "knowledge"))):
        if not f.endswith(".md"):
            continue
        src = os.path.join(FW, "knowledge", f)
        meta, _ = front_matter(src)
        for dest in (claude, gh):
            shutil.copy(src, os.path.join(dest, "knowledge", f))
        used_by = sorted(find_users(f[:-3]))
        rows.append(f"| [{f}]({f}) | {meta.get('topic', '')} | {meta.get('owner', '')} | {meta.get('last_verified', '')} | {', '.join(used_by)} |")
    readme = ("# Knowledge index (generated; edit framework/knowledge/)\n\n"
              "Facts here are leads to re-verify against the build. No counts live here; run `tools/index/query.py`.\n\n"
              "| File | Topic | Owner | Last verified | Used by |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
    for dest in (claude, gh):
        with open(os.path.join(dest, "knowledge", "README.md"), "w", encoding="utf-8") as fh:
            fh.write(readme)

    # Skills (copied whole, minus evals)
    for n in sorted(os.listdir(os.path.join(FW, "skills"))):
        src = os.path.join(FW, "skills", n)
        if not os.path.isdir(src):
            continue
        for dest in (claude, gh):
            d = os.path.join(dest, "skills", n)
            shutil.rmtree(d, ignore_errors=True)
            shutil.copytree(src, d, ignore=shutil.ignore_patterns("evals"))

    # Agents
    for f in sorted(os.listdir(os.path.join(FW, "agents"))):
        if not f.endswith(".md"):
            continue
        src = os.path.join(FW, "agents", f)
        shutil.copy(src, os.path.join(claude, "agents", f))
        shutil.copy(src, os.path.join(gh, "agents", f[:-3] + ".agent.md"))


def find_users(topic):
    """Which skills and agents reference a knowledge topic. Drives the generated 'Used by' column."""
    users = set()
    for sub in ("skills", "agents"):
        base = os.path.join(FW, sub)
        for dirpath, _, files in os.walk(base):
            for f in files:
                if f.endswith(".md"):
                    with open(os.path.join(dirpath, f), encoding="utf-8", errors="replace") as fh:
                        if topic in fh.read():
                            users.add(os.path.relpath(dirpath if sub == "skills" else os.path.join(dirpath, f[:-3]), base).split(os.sep)[0])
    return users


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if not a.check:
        render(ROOT)
        print("rendered .claude/ and .github/ from framework/")
        return 0
    tmp = tempfile.mkdtemp()
    render(tmp)
    diffs = []
    for rel in ("CLAUDE.md", ".claude/knowledge", ".claude/skills", ".claude/agents",
                ".github/instructions", ".github/knowledge", ".github/skills", ".github/agents"):
        a_path, b_path = os.path.join(ROOT, rel), os.path.join(tmp, rel)
        if os.path.isdir(b_path):
            cmp = filecmp.dircmp(a_path, b_path) if os.path.isdir(a_path) else None
            if cmp is None or cmp.diff_files or cmp.left_only or cmp.right_only:
                diffs.append(rel)
        elif not (os.path.exists(a_path) and filecmp.cmp(a_path, b_path, shallow=False)):
            diffs.append(rel)
    if diffs:
        print("rendered outputs are stale: " + ", ".join(diffs) + ". Run tools/build/render.py and commit.")
        return 1
    print("rendered outputs are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
