#!/usr/bin/env python3
"""Deterministic report writer for story-impact. stdlib only.

  python3 write_report.py --id 1234 --slug risk-rating --classified classified.json [--root .]

classified.json: list of {api, layer, type, ownership, changeType, impact, scale, hop, evidence, confidence, note}
"""
import argparse, json, os, subprocess, sys

def stamp(root):
    try:
        out = subprocess.check_output([sys.executable, os.path.join(root, "tools/index/query.py"), "stamp", "--root", root, "--index", os.path.join(root, "index")])
        return json.loads(out)
    except Exception as e:
        return {"commit": "unknown", "error": str(e)}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--id", required=True); ap.add_argument("--slug", required=True)
    ap.add_argument("--classified", required=True); ap.add_argument("--root", default=".")
    a = ap.parse_args()
    with open(a.classified) as fh:
        rows = json.load(fh)
    st = stamp(a.root)
    out_dir = os.path.join(a.root, "ai-context", f"{a.id}-{a.slug}")
    os.makedirs(out_dir, exist_ok=True)
    by_impact = {}
    for r in rows:
        by_impact[r["impact"]] = by_impact.get(r["impact"], 0) + 1
    lines = [f"# Impact: {a.id} {a.slug}", "",
             f"Index commit `{st.get('commit','unknown')[:12]}`, index version {st.get('indexVersion','?')}, built {st.get('builtAt','?')}.", "",
             "| Impact | Count |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(by_impact.items())]
    lines += ["", "| Component | Layer | Type | Ownership | Change | Impact | Scale | Hop | Evidence | Confidence |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| `{r['api']}` | {r.get('layer','')} | {r.get('type','')} | {r.get('ownership','')} | {r.get('changeType','')} | {r['impact']} | {r.get('scale','')} | {r.get('hop','')} | `{r.get('evidence','')}` | {r['confidence']} |")
    unver = [r for r in rows if r["confidence"] == "Unverifiable"]
    lines += ["", "## Unverifiable", ""] + ([f"- `{r['api']}`: {r.get('note','')}" for r in unver] or ["- none"])
    lines += ["", "## Decisions required", "", "- (owner role): ...", "", "_Generated by write_report.py; the model adds framing, triage reasons and manual-check findings above the tables._"]
    path = os.path.join(out_dir, "impact.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(path)

if __name__ == "__main__":
    main()
